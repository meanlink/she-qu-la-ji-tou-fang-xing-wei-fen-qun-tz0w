CREATE TABLE IF NOT EXISTS offline_batches (
    id INT AUTO_INCREMENT PRIMARY KEY,
    client_batch_id VARCHAR(64) NOT NULL UNIQUE,
    submitted_by VARCHAR(40) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (submitted_by) REFERENCES staff(username)
) CHARACTER SET utf8mb4;
CREATE TABLE IF NOT EXISTS offline_backfills (
    id INT AUTO_INCREMENT PRIMARY KEY,
    batch_id INT NOT NULL,
    client_record_id VARCHAR(64) NOT NULL UNIQUE,
    point_id INT NOT NULL,
    point_revision INT NOT NULL,
    sample_day DATE NOT NULL,
    slot ENUM('morning','midday','evening') NOT NULL,
    total INT NOT NULL,
    correct INT NOT NULL,
    overflow INT NOT NULL,
    task_id INT,
    state ENUM('booked','pending','returned') NOT NULL,
    reason VARCHAR(32) NOT NULL DEFAULT '',
    window_id INT,
    captured_at DATETIME,
    submitted_by VARCHAR(40) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_by VARCHAR(40),
    decided_at TIMESTAMP NULL,
    decision_note VARCHAR(240),
    CHECK (total BETWEEN 5 AND 1000),
    CHECK (correct BETWEEN 0 AND total),
    CHECK (overflow BETWEEN 0 AND total),
    INDEX (state,id),
    INDEX (batch_id),
    INDEX (point_id,point_revision,sample_day,slot),
    UNIQUE (window_id),
    FOREIGN KEY (batch_id) REFERENCES offline_batches(id),
    FOREIGN KEY (point_id) REFERENCES disposal_points(id),
    FOREIGN KEY (task_id) REFERENCES outreach_tasks(id),
    FOREIGN KEY (window_id) REFERENCES sampling_windows(id),
    FOREIGN KEY (submitted_by) REFERENCES staff(username),
    FOREIGN KEY (decided_by) REFERENCES staff(username)
) CHARACTER SET utf8mb4;
